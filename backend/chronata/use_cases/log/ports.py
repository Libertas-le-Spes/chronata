from contextlib import AbstractContextManager
from dataclasses import dataclass
from datetime import datetime
from typing import Callable, Protocol

from chronata.timekeeping.hours.label_hours import LabelHours
from chronata.timekeeping.hours.working_day import WorkingDay
from chronata.timekeeping.pc.pc_sessions import Boot
from chronata.timekeeping.record.record import Entry
from chronata.timekeeping.record.stamps import Stamp
from chronata.use_cases.log.outcome import UserError


class SaveError(Exception):
    pass


class RecordStore(Protocol):
    def entries(self) -> list[Entry]: ...
    def append(self, kind: str, data: dict, now: datetime) -> Entry: ...
    def head(self) -> tuple[int, str] | None: ...
    def hash_of(self, seq: int) -> str | None: ...
    def problems(self) -> list[str]: ...


class History(Protocol):
    def keeps_history(self) -> bool: ...
    def commit(self, message: str) -> None: ...
    def rewrites(self) -> list[str]: ...


class LabelHoursStore(Protocol):
    def load(self) -> LabelHours: ...
    def save_hours(self, label: str, hours: WorkingDay | None) -> None: ...
    def save_default_label(self, label: str) -> None: ...
    def rename(self, old: str, new: str) -> None: ...


class PowerHistory(Protocol):
    def boots(self) -> list[Boot]: ...
    def current_boot_id(self) -> str: ...


class CannotCheck(Exception):
    pass


class Timestamper(Protocol):
    def stamp(self, seq: int, record_hash: str) -> tuple[list[Stamp], list[str]]: ...
    def stamps(self) -> list[Stamp]: ...
    def problems(self) -> list[str]: ...


class Place(Protocol):
    id: str
    kind: str
    name: str
    target: str


@dataclass(frozen=True)
class PlaceKindDescription:
    label: str
    asks_for: str
    example: str
    on_this_computer: bool
    needs_folder: bool
    needs_login: bool
    explanation: str


class Places(Protocol):
    def places(self) -> list[Place]: ...
    def kinds(self) -> dict[str, PlaceKindDescription]: ...
    def add(self, kind: str, name: str, target: str, username: str, password: str, folder: str) -> Place: ...
    def remove(self, place_id: str) -> Place: ...
    def deliver(self, place: Place, bundle: dict[str, bytes]) -> None: ...


class SaveRecord(Protocol):
    def last(self, place_id: str) -> dict: ...
    def remember(self, place_id: str, when: datetime, error: str | None) -> None: ...


class Desktop(Protocol):
    def notify(self, summary: str, body: str = "", on_click: Callable[[], None] | None = None, click_label: str = "Open") -> None: ...
    def open_page(self, url: str) -> None: ...
    def can_ask(self) -> bool: ...
    def ask(self, question: str, suggested: str) -> str | None: ...
    def choose(self, question: str, options: list[str]) -> str | None: ...


class Secrets(Protocol):
    def keep(self, key: str, secret: str) -> None: ...
    def find(self, key: str) -> str | None: ...
    def forget(self, key: str) -> None: ...


class NotPrivate(UserError):
    pass


class PrivateFolder(Protocol):
    def write(self, name: str, text: str) -> None: ...
    def read(self, name: str) -> str | None: ...
    def forget(self, name: str) -> None: ...


class Page(Protocol):
    def open(self, section: str = "") -> None: ...


WriteLock = Callable[[], AbstractContextManager]
Clock = Callable[[], datetime]
