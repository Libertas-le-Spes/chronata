from contextlib import AbstractContextManager
from datetime import datetime, time
from typing import Callable, Protocol

from chronata.timekeeping.pc_sessions import Boot
from chronata.timekeeping.record import Entry
from chronata.timekeeping.stamps import Stamp
from chronata.timekeeping.working_day import WorkingDay


class SaveError(Exception):
    pass


class RecordStore(Protocol):
    def entries(self) -> list[Entry]: ...
    def append(self, kind: str, data: dict, now: datetime) -> Entry: ...
    def head(self) -> tuple[int, str] | None: ...
    def hash_of(self, seq: int) -> str | None: ...
    def problems(self) -> list[str]: ...


class History(Protocol):
    def commit(self, message: str) -> None: ...
    def rewrites(self) -> list[str]: ...


class WorkingDayStore(Protocol):
    def load(self) -> WorkingDay: ...
    def save(self, shift_start: time, shift_end: time, lunch_start: time, lunch_minutes: int) -> None: ...


class PowerHistory(Protocol):
    def boots(self) -> list[Boot]: ...
    def current_boot_id(self) -> str: ...


class Timestamper(Protocol):
    def stamp(self, seq: int, record_hash: str) -> tuple[list[Stamp], list[str]]: ...
    def stamps(self) -> list[Stamp]: ...
    def check(self, stamp: Stamp, record_hash: str) -> str | None: ...


class Place(Protocol):
    id: str
    kind: str
    name: str
    target: str


class Places(Protocol):
    def places(self) -> list[Place]: ...
    def kinds(self) -> dict[str, str]: ...
    def add(self, kind: str, name: str, target: str, username: str, password: str) -> Place: ...
    def remove(self, place_id: str) -> Place: ...
    def deliver(self, place: Place, bundle: dict[str, bytes]) -> None: ...
    def last_save(self, place_id: str) -> dict: ...
    def remember(self, place_id: str, when: datetime, error: str | None) -> None: ...


class Desktop(Protocol):
    def notify(self, summary: str, body: str = "", on_click: Callable[[], None] | None = None, click_label: str = "Open") -> None: ...
    def open_page(self, url: str) -> None: ...


WriteLock = Callable[[], AbstractContextManager]
Clock = Callable[[], datetime]
